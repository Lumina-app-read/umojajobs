export type CountryIso2 = (typeof AFRICAN_COUNTRIES)[number]['iso2'];

/** Nombre attendu d'États africains membres de l'ONU. */
export const AFRICAN_COUNTRY_COUNT = 54;

const REGIONAL_INDICATOR_OFFSET = 0x1f1e6 - 'A'.charCodeAt(0);

/**
 * Drapeau emoji d'un pays, calculé à partir de son code ISO alpha-2
 * (deux indicateurs régionaux Unicode). Seule exception autorisée aux emojis dans l'interface.
 */
export function flagEmoji(iso2: string): string {
  if (!/^[A-Z]{2}$/.test(iso2)) {
    throw new Error(`Code pays ISO alpha-2 invalide : ${iso2}`);
  }
  return String.fromCodePoint(
    ...[...iso2].map((letter) => letter.charCodeAt(0) + REGIONAL_INDICATOR_OFFSET),
  );
}

/** Nom usuel d'un pays dans la langue de l'interface ; le code ISO si le pays est inconnu. */
export function countryName(iso2: string, locale: string): string {
  const country = AFRICAN_COUNTRIES.find((entry) => entry.iso2 === iso2);
  if (!country) return iso2;
  return locale === 'fr' ? country.nameFr : country.nameEn;
}

export function isAfricanCountryIso2(value: string): value is CountryIso2 {
  return AFRICAN_COUNTRIES.some((country) => country.iso2 === value);
}
